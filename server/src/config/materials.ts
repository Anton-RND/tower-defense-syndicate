import type { MetalId } from './workshop.js';

/**
 * Четыре высокотехнологичных материала — замена единой донатной валюты.
 *
 * Почему не одна валюта. Универсальная «премиум-монета» продаёт игроку одно и то
 * же решение за три разные боли: ускориться, купить слот, усилить оборону. Игрок
 * копит её и тратит туда, где удобнее ему, а не там, где дизайн хотел удержать
 * темп. Разделение на четыре роли делает цену каждой услуги отдельной: скип
 * таймера больше не конкурирует с покупкой робота-строителя за один баланс, а
 * вольфрам нельзя «съесть» досрочно.
 *
 * РОЛИ (меняются только здесь, вместе с ревью в PR — см. шапку workshop.ts):
 *  - asterium — универсальный донорно-премиальный материал. Единственный из четырёх
 *    покупается за реальные деньги и потому единственный хранит пару кошельков
 *    { purchased, earned }: возврат платежа обязан снимать купленное, а не заработанное
 *    (см. economy/wallet.refundAsterium). Покупает глобальные улучшения (слоты
 *    роботов-строителей, основание клана) и перегоняется в базовые металлы на
 *    «Молекулярном станке».
 *  - chronium — манипуляция временем. Списание за мгновенное ускорение стройки,
 *    крафта и будущих исследований. 1 единица срезает ровно CHRONIUM_MS_PER_UNIT.
 *  - wolfram — суровый индастриал. Сырьё тяжёлых чертежей: броня башен,
 *    бронебойные снаряды, рельсотроны, ключевые узлы боевых дронов.
 *  - stanium — тактическое PvP-вещество. Заряд станиумного модуля базы: снижает
 *    скорость наступающих роботов противника на (1 - STANIUM_SPEED_MULTIPLIER).
 *
 * Все четыре — взаимозаменяемые единицы, поэтому плоские счётчики, а не сущности.
 */

export const TECH_MATERIAL_IDS = ['asterium', 'chronium', 'wolfram', 'stanium'] as const;
export type TechMaterialId = (typeof TECH_MATERIAL_IDS)[number];

/**
 * Материалы, которые могут стоять в стоимости чертежа (MaterialCost).
 * Астерия здесь нет намеренно: это деньги, а не сырьё. Смешай его с вольфрамом —
 * и донатный кошелёк станет расходником крафта, а рефанд платежа начнёт отменять
 * уже собранные игроком башни.
 */
export const CRAFT_TECH_IDS = ['chronium', 'wolfram', 'stanium'] as const;
export type CraftTechId = (typeof CRAFT_TECH_IDS)[number];

/** Кошельки астерия: купленный за рубли и заработанный игрой. */
export type AsteriumWalletName = 'purchased' | 'earned';
export interface AsteriumWallet {
  purchased: number;
  earned: number;
}

/** Сырьевые материалы — плоские счётчики (единицы взаимозаменяемы). */
export interface TechWallet {
  chronium: number;
  wolfram: number;
  stanium: number;
}

const techSet: ReadonlySet<string> = new Set(TECH_MATERIAL_IDS);
const craftSet: ReadonlySet<string> = new Set(CRAFT_TECH_IDS);

/** Guard'ы обязательны: параметры приходят из HTTP и юнионом не являются. */
export function isTechMaterialId(value: string): value is TechMaterialId {
  return techSet.has(value);
}
export function isCraftTechId(value: string): value is CraftTechId {
  return craftSet.has(value);
}
export function isAsteriumWallet(value: string): value is AsteriumWalletName {
  return value === 'purchased' || value === 'earned';
}

export function emptyAsterium(): AsteriumWallet {
  return { purchased: 0, earned: 0 };
}

export function emptyTech(): TechWallet {
  return { chronium: 0, wolfram: 0, stanium: 0 };
}

/** Подписи для витрины и журнала: одна формулировка на весь продукт. */
export const TECH_LABEL: Readonly<Record<TechMaterialId, { label: string; role: string }>> = {
  asterium: { label: 'Астерий', role: 'Донорно-премиальный материал: глобальные улучшения и переработка в металлы' },
  chronium: { label: 'Хрониум', role: 'Ускорение времени: мгновенное завершение стройки и исследований' },
  wolfram: { label: 'Вольфрам', role: 'Тяжёлое производство: броня башен, рельсотроны, узлы дронов' },
  stanium: { label: 'Станиум', role: 'Тактическое PvP: станиумный модуль базы замедляет роботов противника' }
};

// ─── Молекулярный станок (астерий → базовые металлы) ────────────────────────────

/**
 * Выход станка на 1 единицу астерия. Коэффициенты ПАДАЮТ по глубине переработки:
 * 10 чёрных металлов → 4 цветных → 1 драгоценный. Это не скидка, а физика процесса:
 * чем чище металл, тем больше астерия уходит на его выделение. Именно падающий
 * коэффициент делает станок аварийным клапаном («некуда тратить — перегоню»), а не
 * бесплатной печатью драгметалла.
 *
 * Обратного маршрута (металлы → астерий) нет по определению: иначе продажа
 * внутриигрового сырья стала бы способом выводить донатную валюту из-под контроля.
 */
export const ASTERIUM_YIELD: Readonly<Record<MetalId, number>> = {
  black_metal: 10,
  colored_metal: 4,
  precious_metal: 1
};

/**
 * Потолок одной закладки станка. Без него «переработать 10^9 астерия» одним
 * запросом создало бы миллионы единиц металла в одном документе — и ровно ту
 * же проблему для баланса, что и разовая выдача драгметалла админом.
 */
export const CONVERSION_MAX_BATCH = 1_000;

// ─── Хрониум (ускорение очередей) ──────────────────────────────────────────────

/**
 * Сколько миллисекунд таймера срезает одна единица хрониума.
 * 60_000 = «1 минута стройки за 1 хрониум» — цифра, которую игрок считает в уме и
 * сверяет с тем, что видит на кнопке. Линейная по остатку: платить за ускорение
 * начатого 10 минут назад процесса дороже, чем за свежий, — контринтуитивно.
 */
export const CHRONIUM_MS_PER_UNIT = 60_000;

/**
 * Минимальный чек. Без него «осталось 20 секунд» стоило бы 1 хрониум, и кнопка
 * превращалась бы в визуальный шум; заодно защищает цену от нулевых значений.
 */
export const CHRONIUM_MIN_COST = 1;

/** Скидка на пачку: «ускорить всё» — самый частый апселл, он обязан быть выгоднее суммы кнопок. */
export const CHRONIUM_BUNDLE_DISCOUNT = 0.9;

/** Потолок одной заявки на ускорение: защита от «слить 10^9 хрониума» одним запросом. */
export const CHRONIUM_MAX_BATCH = 100_000;

// ─── Станиум (поле замедления) ─────────────────────────────────────────────────

/**
 * Сколько миллисекунд работы станиумного модуля даёт одна единица.
 * 15 минут — осознанный «тактический» масштаб: модуль ставят перед ожидаемой
 * атакой, а не держат включённым постоянно (см. STANIUM_FIELD_MAX_MS).
 */
export const STANIUM_MS_PER_UNIT = 15 * 60_000;

/**
 * Множитель скорости наступающих роботов при активном модуле.
 * 0.75 = «−25% скорости»: роботы дольше остаются под огнём башен, поэтому эффект
 * сильнее, чем кажется по цифре, — и ровно поэтому он покупается станиумом, а не
 * раздаётся бесплатно.
 */
export const STANIUM_SPEED_MULTIPLIER = 0.75;

/** Потолок одной заправки модуля. */
export const STANIUM_MAX_BATCH = 96;

/**
 * Крышка накопленного срока: 24 часа. Зарядка «впрок» превращает модуль в
 * постоянную привилегию и убивает смысл покупать станиум перед боем.
 */
export const STANIUM_FIELD_MAX_MS = 24 * 60 * 60_000;
