/**
 * Стартовый комплект новичка.
 *
 * ПОЧЕМУ ЭТО КОНФИГ, А НЕ ОКРУЖЕНИЕ. Значения меняют ради баланса игры, поэтому
 * они обязаны проходить ревью в PR и фиксироваться тегом релиза — ровно тот же
 * аргумент, что и в шапке config/workshop.ts. Подкрутить щедрость новичка правкой
 * .env без ревью — значит слить экономику и не уметь объяснить игрокам, откуда
 * взялся нерф.
 *
 * ПОЧЕМУ ОН ВООБЩЕ СУЩЕСТВУЕТ. До этого файла аккаунт создавался с нулями во всех
 * кошельках (`createAccount`), а таблица чертежей требовала хлам (`chips`,
 * `batteries`, `ammo_casings`) в КАЖДОМ тир-1 и тир-2 предмете. Хлам же рождается
 * только из боевого лута (`raid/loot.ts`), лут — только из рейда, а рейд требует
 * дрон, который тоже стоит хлам. Замкнутый круг: новичок не мог построить ничего,
 * потому что первое действие любого размера требовало ресурс, выдаваемое за
 * действие, которое невозможно начать без этого ресурса.
 *
 * ТРЕБОВАНИЕ К СОСТАВУ (проверяется тестом `user.starter.test.ts`, а не человеком):
 * комплекта обязано хватить одновременно на (а) первого дрона, (б) первую лазерную
 * турель и (в) первый рудный бур — иначе круг не разомкнут, а лишь сдвинут. Отсюда:
 *   drone_cargo_mk1  = 150 железа + 150 кремния + 2 батареи
 *   tower_laser_mk1  = 200 железа + 100 кремния + 2 чипа
 *   bore_ore_mk1     = 250 железа + 120 кремния + 60 чёрмета
 *   первая стена     =  40 железа +   2 чёрмета
 *   вместе           = 640 железа + 370 кремния + 62 чёрмета + 2 батареи + 2 чипа
 * Взято с запасом (~1,4× по железу, ~1,35× по кремнию, ~1,6× по чёрмету), потому что
 * этой же пачкой игрок платит за вторые и третьи стены, и отказ «не хватило 50
 * железа» на пятой минутке игры — худший возможный первый опыт.
 *
 * ПОЧЕМУ БУР ВОШЁЛ В КОМПЛЕКТ. До него первый шаг в завод был недоступен новичку
 * вообще: ни одно сооружение реестра не покупалось на стартовые 600 железа и 20
 * чёрмета — дешевле всех были силос (300 железа + 100 чёрмета) и крио-контур
 * (400 железа + 120 цветмета, которого на старте ноль). Мастерская открывалась,
 * завод нет. Это ровно тот замкнутый круг, что описан выше про хлам, только этажом
 * выше: ставка добычи не росла ни от чего, кроме платного «Добыча ×2».
 *
 * ПОЧЕМУ ТАК МАЛО ХЛАМА (16 единиц на складе в 20 000). Комплект открывает дверь,
 * а не кормит игру. Постоянный кран хлама — боевой лут и отражённые рейды; если
 * раздать его здесь, цех переработки и PvP потеряют смысл. 16 единиц = ровно два
 * первых предмета и ничего лишнего.
 *
 * ПОЧЕМУ НЕТ АСТЕРИЯ. Астерий — единственная валюта с ценой в реальных рублях
 * (config/shop.ts), и бесплатная его выдача создаёт альт-ферму: основание клана
 * (250 астерия, config/clans.ts) стало бы бесплатным. Новичок получает сырьё,
 * но не деньги.
 *
 * ПОЧЕМУ НЕТ СЕК. SEC — деньги чёрного рынка: они капают из ASIC-стоек и тратятся
 * на P2P-лоты. Бесплатный SEC означал бы бесплатный вход в торговлю.
 */
