/**
 * Кланы (Часть 2).
 *
 * СТОИМОСТЬ ОСНОВАНИЯ И ПОТОЛОК УЧАСТНИКОВ — БАЛАНСНОЕ РЕШЕНИЕ, поэтому они здесь, а
 * не в .env: правка обязана идти через ревью в PR, а не через переменную на проде
 * (тот же принцип, что у наград рефералов в modules/social и цен строителей в
 * config/workshop.ts). Антифрод-потолки и окно подтверждения — наоборот, в
 * LimitsConfig.clan: их крутят, не трогая экономику.
 *
 * ПОЧЕМУ КЛАН СТОИТ АСТЕРИЯ, А НЕ МЕТАЛЛА. Астерий — единственная валюта, которая
 * приходит из реальных денег и имеет рыночную цену «здесь и сейчас». Металл игрок
 * наработает за вечер, и бесплатное основание клана превратится в фабрикацию
 * «альтов-кланов» для фарма казны. 250 единиц = примерно один малый пак (500 за ₽49),
 * то есть клан стоит денег, но не запредельных.
 */

/** Цена основания клана, единицы критания (списывается по правилам wallet.spendAsterium). */
export const CLAN_CREATE_COST = 250;

/** Потолок участников в одном клане: держим в пределах одного документа (16 МБ — не предел). */
export const CLAN_MAX_MEMBERS = 50;

/** Правила имени: нормализация обязательна, иначе «Клан » и «клан » — два разных клана. */
export const CLAN_NAME_MIN_LENGTH = 3;
export const CLAN_NAME_MAX_LENGTH = 24;

/**
 * Допустимые символы: буквы Юникода (включая кириллицу), цифры, один дефис и одно
 * подчёркивание внутри имени. Эмодзи, управляющие символы и «свернутые» пробелы
 * вырезаны: имя попадает в чат, в таблицу кланов и в заголовок клановой войны.
 */
export const CLAN_NAME_PATTERN = /^[\p{L}\p{N}][\p{L}\p{N}_ -]*[\p{L}\p{N}]$/u;

/** Короткий тег клана для интерфейса войн: 2-6 символа, заглавные буквы/цифры. */
export const CLAN_TAG_MIN_LENGTH = 2;
export const CLAN_TAG_MAX_LENGTH = 6;
export const CLAN_TAG_PATTERN = /^[A-Z0-9А-ЯЁ]{2,6}$/;

/** Сколько металлов один клан может накопить в казне: потолок размера документа. */
export const CLAN_TREASURY_CAP = 10_000_000;

/** Максимум разового взноса: защищает от «сдать всё и пожалеть» при ручном разборе. */
export const CLAN_MAX_DEPOSIT_UNITS = 1_000_000;
