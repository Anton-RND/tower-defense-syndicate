import { materialEntries, type ItemKind, type MaterialCost } from './workshop.js';

/**
 * Карта базы: сетка, точки входа роботов, стены и требования проходимости (Шаг 3).
 *
 * Почему это конфиг баланса, а не окружение (та же логика, что в workshop.ts):
 * размер сетки и цена стены определяют сложность игры, меняются по результатам
 * балансных прогонов и обязаны фиксироваться тегом релиза. «Поднять MAX_WALLS
 * правкой .env на проде» — это патч баланса без ревью.
 *
 * Почему сетка хранится списком занятых клеток, а не матрицей 16×16: на поле
 * 256 клеток игрок обычно занимает десятки. Полная матрица — 256 поддокументов
 * на игрока и O(256) на каждое чтение, ради экономии O(k) на записи, которой всё
 * равно предшествует валидация по всем занятым клеткам.
 */

/** Координата клетки. x — столбец (0..width-1), y — строка (0..height-1). */
export interface Cell {
  x: number;
  y: number;
}

// ─── Поле ─────────────────────────────────────────────────────────────────────

/**
 * Размер поля по умолчанию. 16×16 — компромисс: достаточно клеток, чтобы лабиринт
 * был осмысленным (≈256 клеток, из них ~240 доступны игроку), и достаточно мало,
 * чтобы BFS считался за микросекунды на каждом сохранении и в каждом бою, а палец
 * на телефоне не попадал в соседнюю клетку.
 */
export const GRID_WIDTH = 16;
export const GRID_HEIGHT = 16;

/**
 * Ворота, через которые роботы атакующего входят на поле.
 *
 * Они СЕРВЕРНЫЕ, игрок их не двигает. Это дыра первого драфта: если `spawn_point`
 * приходит с клиента, достаточно объявить точку входа впритык к штабу — путь в одну
 * клетку пройдёт любую проверку «лабиринт проходим», база станет не обороняемой,
 * а бой — мгновенным. То же самое для «удалить все точки входа».
 *
 * Четверо ворот по серединам сторон, каждые в две клетки: подходы симметричны, и
 * игрок обязан закрывать все четыре, а не один избранный.
 */
export const SPAWN_CELLS: readonly Cell[] = [
  { x: 0, y: 7 },
  { x: 0, y: 8 },
  { x: GRID_WIDTH - 1, y: 7 },
  { x: GRID_WIDTH - 1, y: 8 },
  { x: 7, y: 0 },
  { x: 8, y: 0 },
  { x: 7, y: GRID_HEIGHT - 1 },
  { x: 8, y: GRID_HEIGHT - 1 }
];

/**
 * Площадки под штаб: игрок выбирает одну. Набор, а не свободная координата, потому
 * что штаб — единственная цель атакующего, и его позиция не должна давать
 * преимущество «поставил в угол, закрыл тремя стенами».
 */
export const HQ_PADS: readonly Cell[] = [
  { x: 7, y: 7 },
  { x: 8, y: 7 },
  { x: 7, y: 8 },
  { x: 8, y: 8 }
];

/** Штаб новичка: база обязана быть валидной до первого действия игрока. */
export const DEFAULT_HQ: Cell = { x: 7, y: 7 };

// ─── Стены ────────────────────────────────────────────────────────────────────

/**
 * Стена — НЕ предмет инвентаря, а расходуемый материал.
 *
 * Собственная сущность на стену означала бы очередь стройки, роботов-строителей и
 * инвентарь на 400 слотов под «поставить плиту». Стена ставится и снимается мгновенно
 * и потому оплачивается напрямую из кошелька материалов — это крупнейший сток железа
 * и цветмета помимо чертежей, и именно он замыкает петлю
 * «бой → хлам → цех → стена → следующая оборона».
 */
export const WALL_CODE = 'structure_wall_mk1';
export const WALL_NAME = 'Бетонная плита';
export const WALL_TIER = 1;

/** Цена одной клетки стены. */
export const WALL_COST: MaterialCost = { ferrum: 40, black_metal: 2 };

/**
 * Доля возврата при сносе. Ниже общей SALVAGE_RATE_DEFAULT: переигрывать планировку
 * бесплатно нельзя, иначе стена перестаёт быть решением и становится расходником.
 * При этом не ноль: игрок, передумавший за минуту, не должен гореть.
 */
export const WALL_SALVAGE_RATE = 0.5;

/** Потолок стен: 120 из ~240 свободных клеток. Дальше поле превращается в кашу и упирается в MIN_PATH. */
export const MAX_WALLS = 120;

// ─── Боевые единицы на карте ──────────────────────────────────────────────────

/**
 * Что можно выставить на оборону. Дроны исключены сознательно: они летают и в бою
 * клетку не занимают, а значит участие в лабиринте им не положено — их роль атаки
 * (Шаг 4). Правка этого списка — единственный способ разрешить новый обороняемый вид.
 */
export const DEPLOYABLE_KINDS: readonly ItemKind[] = ['tower', 'weapon'];

/**
 * Блокируют ли элементы движение роботов.
 *
 * Флаг конфигурационный, потому что это развилка дизайна, а не баг: если башня
 * перестанет быть препятствием, лабиринт придётся строить только из стен, и цена
 * стены вырастет. ВАЖНО: резолвер боя (Шаг 4) обязан читать ЭТОТ ЖЕ флаг —
 * расхождение валидатора и симуляции даёт карту «проходимую» на бумаге и
 * застревающую в бою.
 */
export const BLOCKS_MOVEMENT: Readonly<Record<'wall' | 'unit', boolean>> = {
  wall: true,
  unit: true
};

/** Сколько единиц техники можно одновременно держать на поле. */
export const MAX_DEPLOYED_UNITS = 24;

// ─── Правила проходимости ─────────────────────────────────────────────────────

/**
 * Минимальная длина кратчайшего маршрута от ворот до штаба, в шагах.
 *
 * От ворот до центра по прямой — 7 шагов (худший подход на пустом поле — 9). Порог 10
 * означает, что хотя бы один изгиб на каждом из четырёх подходов построить придётся,
 * но спирали не требуется.
 *
 * Это ПРЕДУПРЕЖДЕНИЕ, а не отказ. Жёсткий запрет на «короткий путь» наказывал бы
 * новичка, который ещё не построил ни одной стены. А вот отсутствия пути — отказ:
 * роботы без маршрута встанут навсегда, и бой не завершится никогда.
 */
export const MIN_PATH_TILES = 10;

/** Сколько отрезанных от ворот проходимых клеток терпимо без предупреждения. */
export const ORPHAN_TOLERANCE = 0;

// ─── Хелперы ──────────────────────────────────────────────────────────────────

export function isDeployableKind(kind: string): kind is ItemKind {
  return (DEPLOYABLE_KINDS as readonly string[]).includes(kind);
}

export function cellEquals(a: Cell, b: Cell): boolean {
  return a.x === b.x && a.y === b.y;
}

/** Человекочитаемая координата для сообщений и meta движений журнала. */
export function formatCell(cell: Cell): string {
  return `${cell.x},${cell.y}`;
}

/** Умножает стоимость материала на целое число единиц (пачка стен, N одинаковых предметов). */
export function scaleMaterial(cost: MaterialCost, count: number): MaterialCost {
  const units = Math.trunc(count);
  if (units <= 0) return {};
  const result: MaterialCost = {};
  for (const [id, amount] of materialEntries(cost)) result[id] = amount * units;
  return result;
}

/** Что вернётся при сносе одной стены (вниз: щедрость на округлении — это эмиссия). */
export const WALL_SALVAGE_COST: MaterialCost = (() => {
  const result: MaterialCost = {};
  for (const [id, amount] of materialEntries(WALL_COST)) {
    const value = Math.floor(amount * WALL_SALVAGE_RATE);
    if (value > 0) result[id] = value;
  }
  return result;
})();

/** Публичная форма правил карты — то, что уходит клиенту в /config (рисовать сетку без угадывания констант). */
export function publicBaseConfig(): Record<string, unknown> {
  return {
    grid: { width: GRID_WIDTH, height: GRID_HEIGHT },
    spawns: SPAWN_CELLS.map((cell) => ({ ...cell })),
    hqPads: HQ_PADS.map((cell) => ({ ...cell })),
    defaultHq: { ...DEFAULT_HQ },
    wall: {
      code: WALL_CODE,
      name: WALL_NAME,
      tier: WALL_TIER,
      cost: { ...WALL_COST },
      salvage: { ...WALL_SALVAGE_COST },
      max: MAX_WALLS
    },
    units: {
      deployableKinds: [...DEPLOYABLE_KINDS],
      max: MAX_DEPLOYED_UNITS,
      blocksMovement: BLOCKS_MOVEMENT.unit
    },
    path: { minTiles: MIN_PATH_TILES, blocksWalls: BLOCKS_MOVEMENT.wall }
  };
}

