/**
 * Валюты журнала. Ресурсы — те же ключи, что в кошельке игрока; астерий —
 * раздельно по кошелькам, чтобы «купленные» и «заработанные» единицы никогда не
 * смешивались; сырьё (хрониум, вольфрам, станиум) — своими, потому что оно
 * покупается за реальные деньги и его выдача обязана быть свёртываемой по SKU;
 * металлы и хлам — своими, потому что по ним строится отчёт «откуда взялся материал».
 */
export type AsteriumCurrency = 'asterium_purchased' | 'asterium_earned';
export type JunkCurrency = `junk_${JunkId}`;
export type LedgerCurrency = ResourceId | MetalId | JunkCurrency | AsteriumCurrency | CraftTechId;

export const ASTERIUM_CURRENCY: Record<AsteriumWalletName, AsteriumCurrency> = {
  purchased: 'asterium_purchased',
  earned: 'asterium_earned'
};

export function junkCurrency(id: JunkId): JunkCurrency {
  return `junk_${id}`;
}

