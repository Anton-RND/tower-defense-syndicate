/**
 * Черновик записи: создаётся чистыми функциями кошелька/экономики вместе с новой
 * учётной записью, а уже потом фиксируется в LedgerStore. Так доменная логика
 * остаётся свободной от I/O и тривиально тестируется.
 */
export interface LedgerDraft {
  userId: string;
  currency: LedgerCurrency;
  /** Знак важнее абсолютного значения: + начисление, − списание. */
  delta: number;
  /** Баланс ПОСЛЕ движения — по нему восстанавливается история без пересчёта. */
  balanceAfter: number;
  reason: LedgerReason;
  refType: LedgerRefType;
  refId: string | null;
  /**
   * Ключ идемпотентности (`order:<id>`, `ad:<sessionId>`, `collect:<userId>:<ts>`).
   * Уникальный индекс в Mongo + Set в памяти: повторный вебхук/ретрай клиента
   * не должен выдать товар второй раз.
   */
  idempotencyKey: string | null;
  ts: Date;
  meta?: Record<string, string | number | boolean | null>;
}

export interface LedgerEntry extends LedgerDraft {
  id: string;
}

export interface LedgerQuery {
  /** Только конкретные причины (например, purchase/refund для сверки с агентом). */
  reasons?: LedgerReason[];
  since?: Date;
  until?: Date;
  limit?: number;
}

/**
 * Ключ идемпотентности. Префикс — по типу источника, `id` — его идентификатор.
 *
 * Два инварианта, и оба обязателен, а не «желателен»:
 *  1. Действие с несколькими валютами (сбор склада, лут, оплата чертежа) ОБЯЗАНО
 *     включать в ключ валюту/материал: иначе вторая запись пачки отбрасывается
 *     уникальным индексом как дубль первой.
 *  2. Если в ключ попадает строка ОТ КЛИЕНТА (заголовок Idempotency-Key), ключ ОБЯЗАН
 *     включать id игрока. Уникальность здесь глобальная, а клиентские ключи повторяются
 *     у разных игроков («1», «retry», счётчик запросов) — без привязки к аккаунту второй
 *     игрок получил бы движение без аудиторского следа. Остальные ключи спасает то, что
 *     они собраны из серверных идентификаторов (order/ad/raid/jobId/contributionId);
 *     образец правильной связки с предпроверкой — `recycleEntryKey` в
 *     workshop/recycle.ts и маршрут /v1/workshop/recycle.
 *
 * Цена нарушения — не падение, а тихая дыра: `appendMany` возвращает число записанных,
 * и HTTP-слой логирует `ledger_drafts_dropped` (см. helpers.accountAction).
 */
export function makeIdempotencyKey(
  prefix:
    | 'order'
    | 'ad'
    | 'raid'
    | 'collect'
    | 'industry'
    | 'event'
    | 'builder'
    | 'build'
    | 'dismantle'
    | 'recycle'
    | 'rush'
    | 'convert'
    | 'stanium'
    | 'deploy'
    | 'starter'
    | 'market'
    | 'clan'
    | 'deposit',
  id: string
): string {
  return `${prefix}:${id}`;
}