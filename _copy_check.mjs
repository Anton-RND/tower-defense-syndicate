// ─── Проверка ────────────────────────────────────────────────────────────────
// [...s].length — по кодовым точкам, а не UTF-16: «—» и эмодзи считаются один раз,
// как их считает браузерный input.maxLength и сервер ВК.
const size = (s) => [...s].length;
// Русская плюрализация: «1 поле / 2 поля / 5 полей». Был захардкожен «полей», из-за чего
// отчёт врал на каждом файле с одним полем — иронично для инструмента, ловящего чужие
// рассинхроны.
const plural = (n, one, few, many) => {
  const m10 = n % 10;
  const m100 = n % 100;
  if (m10 === 1 && m100 !== 11) return one;
  if (m10 >= 2 && m10 <= 4 && (m100 < 10 || m100 >= 20)) return few;
  return many;
};
let bad = 0;
const line = (limit, label, s) => {
  const n = size(s);
  const ok = limit == null || n <= limit;
  if (!ok) bad += 1;
  console.log(String(n).padStart(4) + (limit ? ' / ' + String(limit).padEnd(4) : ' /  —  ') +
    (ok ? ' OK  ' : ' BIG ') + label);
};

console.log('== Утверждено ==');
