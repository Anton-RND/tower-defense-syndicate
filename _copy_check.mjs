// ─── Проверка ────────────────────────────────────────────────────────────────
// [...s].length — по кодовым точкам, а не UTF-16: «—» и эмодзи считаются один раз,
// как их считает браузерный input.maxLength и сервер ВК.
const size = (s) => [...s].length;
let bad = 0;
const line = (limit, label, s) => {
  const n = size(s);
  const ok = limit == null || n <= limit;
  if (!ok) bad += 1;
  console.log(String(n).padStart(4) + (limit ? ' / ' + String(limit).padEnd(4) : ' /  —  ') +
    (ok ? ' OK  ' : ' BIG ') + label);
};

console.log('== Утверждено ==');
line(60, 'слоган', SLOGAN);
line(80, 'краткое описание', SHORT);
line(1000, 'описание (полное)', LONG);
line(1000, 'описание (компактное)', COMPACT);
line(null, 'шеринг: заголовок', SHARE_TITLE);
line(120, 'шеринг: сообщение', SHARE_MESSAGE);
line(80, 'шеринг: описание (= краткое)', SHARE_DESCRIPTION);

console.log('\n== Запасные: слоган (лимит 60) ==');
for (const s of spareSlogans) line(60, s, s);
console.log('\n== Запасные: краткое (лимит 80) ==');
for (const s of spareShorts) line(80, s, s);

// Пробельные артефакты ловятся отдельно: сдвоенный пробел в поле кабинета выглядит
// багом, а глазами в блоке текста не виден.
console.log('\n== Гигиена утверждённых строк ==');
const hygiene = [['слоган', SLOGAN], ['краткое', SHORT], ['описание', LONG], ['компактное', COMPACT], ['шеринг', SHARE_MESSAGE]];
for (const [label, s] of hygiene) {
  const issues = [];
  if (/[ \t]{2,}/.test(s)) issues.push('сдвоенный пробел');
  if (/^\s|\s$/.test(s)) issues.push('висит по краям');
  if (/\t/.test(s)) issues.push('табуляция');
  if (s.split('\n').some((l) => /[ \t]$/.test(l))) issues.push('пробел перед переносом');
  console.log('  ' + label.padEnd(12) + (issues.length ? 'PROBLEM: ' + issues.join(', ') : 'чисто'));
}

// ─── Дрейф между файлами ─────────────────────────────────────────────────────
// Сегодняшний прогон поймал не только перебор длины: в VkSocialManager.ts лежало
// «майни металл», когда каталог уже утвердил «майни SEC». Два файла жили независимо, и
// глаз это не ловит. Ниже — утверждение, что каждая ФИНАЛ-строка реально стоит в своих
// файлах дословно; рассинхрон становится падающей командой, а не невидимой правкой.
console.log('\n== Дрейф: строки ФИНАЛ в целевых файлах ==');
const { readFileSync } = await import('node:fs');
const ROOT = new URL('.', import.meta.url);
// Нормализуем перевод строки: файлы в репозитории CRLF, литералы здесь LF — без этого
// многострочное LONG не совпало бы никогда и проверка давала бы ложный красный.
const read = (p) => readFileSync(new URL(p, ROOT), 'utf8').replace(/\r\n/g, '\n');

const driftTargets = [
  ['frontend/src/vk/VkSocialManager.ts', [['title', SHARE_TITLE], ['message', SHARE_MESSAGE], ['description', SHORT]]],
  ['package.json', [['slogan', SLOGAN]]],
  ['server/package.json', [['slogan', SLOGAN]]],
  ['VK_CATALOG.md', [['slogan', SLOGAN], ['short', SHORT], ['long', LONG], ['compact', COMPACT], ['share', SHARE_MESSAGE]]]
];
for (const [file, fields] of driftTargets) {
  let content;
  try {
    content = read(file);
  } catch {
    bad += 1;
    console.log('  MISSING  ' + file);
    continue;
  }
  const misses = fields.filter(([, s]) => !content.includes(s)).map(([label]) => label);
  if (misses.length) {
    bad += misses.length;
    console.log('  DRIFT    ' + file + ' — нет дословно: ' + misses.join(', '));
  } else {
    console.log('  ' + 'ok'.padEnd(9) + file + ' (' + fields.length + ' полей)');
  }
}

console.log('\n' + (bad === 0 ? 'ВСЕ УТВЕРЖДЁННЫЕ СТРОКИ В ЛИМИТАХ И БЕЗ ДРЕЙФА' : 'ПРОБЛЕМ: ' + bad) + '\n');
process.exit(bad === 0 ? 0 : 1);